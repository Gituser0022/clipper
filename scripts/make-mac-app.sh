#!/usr/bin/env bash
# Build Clipper.app, a double-clickable launcher for the Clipper web UI (macOS).
#
#   bash scripts/make-mac-app.sh                  # -> ~/Applications/Clipper.app
#   APP_DIR=/some/folder bash scripts/...         # -> /some/folder/Clipper.app
#
# The app starts `clipper serve` in the background (if it isn't running yet)
# and opens http://localhost:8000. It runs this checkout's .venv, so rerun the
# script if you move the repo.
set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd -P)"
CLIPPER="$REPO/.venv/bin/clipper"
APP_DIR="${APP_DIR:-$HOME/Applications}"
case "$APP_DIR" in
  *.app) APP="$APP_DIR" ;;
  *) APP="$APP_DIR/Clipper.app" ;;
esac
BUNDLE_ID="local.clipper"

if [[ ! -x "$CLIPPER" ]]; then
  cat >&2 <<EOF
Clipper isn't installed in $REPO/.venv yet. Set it up first:

  brew install python ffmpeg node
  cd $(printf '%q' "$REPO")
  /opt/homebrew/bin/python3 -m venv .venv
  .venv/bin/pip install -e .

then run this script again.
EOF
  exit 1
fi

# Only ever replace a bundle this script made.
if [[ -e "$APP" ]]; then
  if ! grep -qs "<string>$BUNDLE_ID</string>" "$APP/Contents/Info.plist"; then
    echo "$APP exists and wasn't made by this script; move it away first." >&2
    exit 1
  fi
  rm -rf "$APP"
fi
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"

# LSUIElement: the launcher only starts the server and opens the browser, then
# exits, so it shouldn't flash a Dock icon or show up in Cmd-Tab. The app can
# still be pinned to the Dock by dragging it there from Finder.
cat > "$APP/Contents/Info.plist" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleName</key><string>Clipper</string>
  <key>CFBundleDisplayName</key><string>Clipper</string>
  <key>CFBundleIdentifier</key><string>$BUNDLE_ID</string>
  <key>CFBundleExecutable</key><string>Clipper</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleIconFile</key><string>Clipper</string>
  <key>CFBundleShortVersionString</key><string>1.0</string>
  <key>CFBundleVersion</key><string>1</string>
  <key>LSMinimumSystemVersion</key><string>11.0</string>
  <key>LSUIElement</key><true/>
</dict>
</plist>
EOF

LAUNCHER="$APP/Contents/MacOS/Clipper"
{
  echo '#!/bin/bash'
  echo '# Clipper.app launcher, generated by scripts/make-mac-app.sh (rerun it to rebuild).'
  echo "REPO=$(printf '%q' "$REPO")"
  cat <<'EOF'
PORT="${CLIPPER_PORT:-8000}"
URL="http://localhost:$PORT"
PROBE="http://127.0.0.1:$PORT/api/jobs"
LOG="$HOME/Library/Logs/Clipper.log"
CLIPPER="$REPO/.venv/bin/clipper"
# Apps started from Finder don't get the shell's PATH: add Homebrew (ffmpeg,
# node) and the venv (yt-dlp).
export PATH="/opt/homebrew/bin:/usr/local/bin:$REPO/.venv/bin:$PATH"

alert() {
  osascript -e 'on run argv' -e 'display alert "Clipper" message (item 1 of argv) as critical' \
    -e 'end run' "$1" >/dev/null 2>&1 || echo "Clipper: $1" >&2
}

running() { curl -fs -o /dev/null --max-time 2 "$PROBE"; }

if [ ! -x "$CLIPPER" ]; then
  alert "$(printf 'Clipper is not installed in %s (no .venv/bin/clipper).\n\nIn Terminal run:\n  cd %q\n  /opt/homebrew/bin/python3 -m venv .venv\n  .venv/bin/pip install -e .\n  brew install ffmpeg node' "$REPO" "$REPO")"
  exit 1
fi

if ! running; then
  mkdir -p "$(dirname "$LOG")"
  cd "$REPO" || { alert "Can't open $REPO"; exit 1; }
  printf '\n=== %s starting Clipper ===\n' "$(date)" >>"$LOG"
  nohup "$CLIPPER" serve --host 127.0.0.1 --port "$PORT" --data "$REPO/data" \
    >>"$LOG" 2>&1 </dev/null &
  pid=$!
  deadline=$((SECONDS + 20))
  until running; do
    if ! kill -0 "$pid" 2>/dev/null; then
      alert "Clipper stopped while starting. Details are in $LOG"
      exit 1
    fi
    if [ "$SECONDS" -ge "$deadline" ]; then
      alert "Clipper didn't start within 20 seconds. Details are in $LOG"
      exit 1
    fi
    sleep 0.25
  done
fi
open "$URL"
EOF
} > "$LAUNCHER"
chmod 755 "$LAUNCHER"

# App icon, made from the PNG in the repo with macOS's own tools.
ICON_PNG="$REPO/scripts/clipper-icon.png"
if [[ -f "$ICON_PNG" ]] && command -v sips >/dev/null && command -v iconutil >/dev/null; then
  ICONSET="$(mktemp -d)/Clipper.iconset"
  mkdir -p "$ICONSET"
  for size in 16 32 128 256 512; do
    sips -z "$size" "$size" "$ICON_PNG" --out "$ICONSET/icon_${size}x${size}.png" >/dev/null
    sips -z $((size * 2)) $((size * 2)) "$ICON_PNG" --out "$ICONSET/icon_${size}x${size}@2x.png" >/dev/null
  done
  iconutil -c icns "$ICONSET" -o "$APP/Contents/Resources/Clipper.icns" || echo "(icon skipped)" >&2
  rm -rf "$(dirname "$ICONSET")"
fi

# Built locally, so there's no quarantine flag; clear it anyway in case the
# repo was downloaded as a zip. Then tell Finder about the new icon.
if command -v xattr >/dev/null; then xattr -dr com.apple.quarantine "$APP" 2>/dev/null || true; fi
LSREGISTER=/System/Library/Frameworks/CoreServices.framework/Frameworks/LaunchServices.framework/Support/lsregister
if [[ -x "$LSREGISTER" ]]; then "$LSREGISTER" -f "$APP" || true; fi
touch "$APP"

cat <<EOF
Built $APP
  Runs:  $CLIPPER serve  (logs: ~/Library/Logs/Clipper.log, clips: $REPO/data/clips)

Open it:          double-click Clipper in Finder ($(dirname "$APP")), or: open $(printf '%q' "$APP")
                  If macOS blocks it the first time: right-click it -> Open -> Open
                  (macOS 15+: System Settings -> Privacy & Security -> Open Anyway).
Add to the Dock:  drag Clipper.app from Finder onto the Dock.
Stop the server:  the Quit button in the web page.
Remove it:        drag it off the Dock, then: rm -rf $(printf '%q' "$APP")
EOF
